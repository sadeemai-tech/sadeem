#!/usr/bin/env node
// ============================================================
// SADEEM — prepare a STATIC electron-updater feed. No upload.
//
//   node scripts/publish-release.mjs
//
// Reads the Windows artifacts produced by `npm run dist:win` from release/,
// computes SHA-512 (base64, the form electron-updater expects) and SHA-256
// (hex), writes website/public/updates/latest.yml, and copies the artifacts
// into website/public/downloads/. The website is a Next static export, so
// `npm run build` inside website/ then places these at out/updates/latest.yml
// and out/downloads/* — upload the contents of website/out/ to your host.
//
// Nothing here talks to a server. Only Node built-ins; no new dependencies.
// ============================================================
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const RELEASE_DIR = path.join(ROOT, 'release');
const UPDATES_DIR = path.join(ROOT, 'website', 'public', 'updates');
const DOWNLOADS_DIR = path.join(ROOT, 'website', 'public', 'downloads');

/** Quote a scalar for YAML so file names / dates cannot change its meaning. */
const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

async function hashesOf(file) {
  const sha512 = createHash('sha512');
  const sha256 = createHash('sha256');
  let size = 0;
  for await (const chunk of fs.createReadStream(file)) {
    sha512.update(chunk);
    sha256.update(chunk);
    size += chunk.length;
  }
  return { sha512: sha512.digest('base64'), sha256: sha256.digest('hex'), size };
}

function newestByMtime(files) {
  return [...files].sort(
    (a, b) => fs.statSync(path.join(RELEASE_DIR, b)).mtimeMs - fs.statSync(path.join(RELEASE_DIR, a)).mtimeMs,
  );
}

async function main() {
  if (!fs.existsSync(RELEASE_DIR)) {
    console.error(`[publish-release] No release/ directory at ${RELEASE_DIR}. Run: npm run dist:win`);
    process.exitCode = 1;
    return;
  }

  const allFiles = fs.readdirSync(RELEASE_DIR);
  const exeFiles = allFiles.filter((f) => /^SADEEM-Setup-.*\.exe$/i.test(f));
  const zipFiles = allFiles.filter((f) => /^SADEEM.*\.zip$/i.test(f));

  if (exeFiles.length === 0) {
    console.error('[publish-release] No SADEEM-Setup-*.exe found in release/. Run: npm run dist:win');
    console.error('[publish-release] Refusing to publish a feed without a real installer (no placeholders).');
    process.exitCode = 1;
    return;
  }

  const pkgVersion = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
  // Prefer the artifact matching package.json. release/ can hold several
  // versions; picking by mtime alone is fragile (equal timestamps, copied
  // files) and once published an older installer silently rolled users back.
  const onVersion = exeFiles.filter((f) => f.toLowerCase() === `sadeem-setup-${pkgVersion.toLowerCase()}.exe`);
  const installer = onVersion[0] ?? newestByMtime(exeFiles)[0];
  const versionMatch = installer.match(/^SADEEM-Setup-(.+)\.exe$/i);
  const version = versionMatch ? versionMatch[1] : '0.0.0-unknown';
  if (version !== pkgVersion) {
    console.warn(`[publish-release] WARNING: no SADEEM-Setup-${pkgVersion}.exe found; using "${installer}" (version ${version}).`);
  }

  // Only include zips that belong to this version; never mix releases in a feed.
  const matchingZips = zipFiles.filter((f) => f.includes(version)).sort();
  const skippedZips = zipFiles.filter((f) => !f.includes(version));
  for (const f of skippedZips) console.warn(`[publish-release] Skipping zip for another version: ${f}`);
  const artifacts = [installer, ...matchingZips];

  const rows = [];
  for (const name of artifacts) {
    const h = await hashesOf(path.join(RELEASE_DIR, name));
    rows.push({ name, ...h });
    console.log(`[publish-release] ${name}  sha256=${h.sha256}  sha512=${h.sha512}  size=${h.size}`);
  }

  fs.mkdirSync(UPDATES_DIR, { recursive: true });
  fs.mkdirSync(DOWNLOADS_DIR, { recursive: true });

  const releaseDate = new Date().toISOString();
  const main = rows[0];
  const yml = [
    '# GENERATED by scripts/publish-release.mjs - do not hand-edit.',
    '# Static electron-updater (generic provider) feed for SADEEM. Regenerate:',
    '#   node scripts/publish-release.mjs',
    `version: ${version}`,
    `releaseDate: ${q(releaseDate)}`,
    'files:',
    ...rows.flatMap((r) => [
      `  - url: ${q(r.name)}`,
      `    sha512: ${q(r.sha512)}`,
      `    size: ${r.size}`,
    ]),
    `path: ${q(main.name)}`,
    `sha512: ${q(main.sha512)}`,
    '',
  ].join('\n');
  const ymlPath = path.join(UPDATES_DIR, 'latest.yml');
  fs.writeFileSync(ymlPath, yml, 'utf8');

  const sums = [
    '# SADEEM release artifact hashes. sha256 = hex, sha512 = base64 (electron-updater format).',
    ...rows.map((r) => `${r.sha256}  ${r.name}  sha512:${r.sha512}`),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(DOWNLOADS_DIR, 'SHA256SUMS.txt'), sums, 'utf8');

  // v11.43 — DO NOT copy the 300+ MB installers into website/public/downloads.
  // Next static deployments ship that folder, which exhausted Vercel Blob's
  // free quota and suspended the store. Real downloads are served from Vercel
  // Blob (see site.ts download.* URLs); the local files are only hashed above.
  // Remove any stale large artifacts a previous publish left behind.
  for (const name of artifacts) {
    try { fs.unlinkSync(path.join(DOWNLOADS_DIR, name)); } catch { /* not present */ }
  }

  console.log('');
  console.log(`[publish-release] Wrote ${path.relative(ROOT, ymlPath)} (version ${version}).`);
  console.log('[publish-release] Kept installers OUT of website/public (Blob serves downloads).');
  console.log('[publish-release] No upload performed. Next:');
  console.log('[publish-release]   1) cd website && npm run build   (static export → website/out/)');
  console.log('[publish-release]   2) upload the CONTENTS of website/out/ to your HTTPS host');
  console.log('[publish-release]   3) verify /updates/latest.yml and /downloads/<artifact> are reachable');
}

main().catch((e) => {
  console.error(`[publish-release] FAILED: ${e instanceof Error ? e.message : String(e)}`);
  process.exitCode = 1;
});
