#!/usr/bin/env node
// ============================================================
// v11.38 — WEBSITE SEO GUARD (source + rendered-build verification)
// ------------------------------------------------------------
// Run from the repo root:  node tests-v1138-seo.mjs
// (No network, no deploy. Build artifacts are optional: when
//  website/.next/server/app exists the guard parses the REAL
//  prerendered <head>, robots.txt.body, sitemap.xml.body and the
//  generated PNG; otherwise it reports SKIP for those checks.)
//
// Enforces:
//   1. unique per-page title/description/canonical/OG/Twitter/hreflang
//   2. Organization + SoftwareApplication + FAQPage JSON-LD, honest $0
//      FREE_SEASON offer (no fake purchasable price, no rating)
//   3. semantic HTML: exactly one h1/page, nav/alt landmarks, bilingual
//   4. sitemap lists every route + stable lastModified; robots -> sitemap
//   5. real 1200x630 OG image generated by ImageResponse
//   6. no superlative / fake-pricing claims in metadata
// Exit 0 = no FAIL; exit 1 = at least one FAIL.
// ============================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('.', import.meta.url));
const WEB = path.join(ROOT, 'website');
const BUILD = path.join(WEB, '.next', 'server', 'app');
const results = [];
const SITE_URL = 'https://sadeem-ai.com';

function check(id, ok, detail, fileLine = '') {
  const status = ok ? 'PASS' : 'FAIL';
  results.push({ id, status, detail, fileLine });
  console.log(`${status} ${id}${fileLine ? ` [${fileLine}]` : ''}: ${detail}`);
  return ok;
}
function note(id, status, detail, fileLine = '') {
  results.push({ id, status, detail, fileLine });
  console.log(`${status} ${id}${fileLine ? ` [${fileLine}]` : ''}: ${detail}`);
}
const read = (rel) => fs.readFileSync(path.join(WEB, rel), 'utf8');
const exists = (rel) => fs.existsSync(path.join(WEB, rel));
const lineOf = (src, needle) => {
  const i = src.split(/\r?\n/).findIndex((l) => l.includes(needle));
  return i >= 0 ? i + 1 : '?';
};
const loc = (rel, needle) => `${rel}:${lineOf(read(rel), needle)}`;
const strip = (s) => s
  .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
  .split(/\r?\n/)
  .map((l) => (/^\s*\/\//.test(l) ? '' : l))
  .join('\n');
const arabic = (s) => /[\u0600-\u06FF]/.test(s);

const ROUTES = [
  { route: '/', key: 'home', file: 'app/layout.tsx', build: 'index.html' },
  { route: '/features', key: 'features', file: 'app/features/layout.tsx', build: 'features.html' },
  { route: '/pricing', key: 'pricing', file: 'app/pricing/layout.tsx', build: 'pricing.html' },
  { route: '/download', key: 'download', file: 'app/download/page.tsx', build: 'download.html' },
  { route: '/docs', key: 'docs', file: 'app/docs/layout.tsx', build: 'docs.html' },
];

const SITEMAP_ROUTES = ['/', '/features', '/download', '/pricing', '/docs', '/changelog', '/auth'];

// ------------------------------------------------------------
// 0. Required files
// ------------------------------------------------------------
const REQUIRED = [
  'lib/site.ts', 'app/layout.tsx', 'app/page.tsx', 'app/features/page.tsx',
  'app/pricing/page.tsx', 'app/download/page.tsx', 'app/docs/page.tsx',
  'app/sitemap.ts', 'app/robots.ts', 'app/opengraph-image.tsx',
  'app/features/layout.tsx', 'app/pricing/layout.tsx', 'app/docs/layout.tsx',
];
const missing = REQUIRED.filter((f) => !exists(f));
check('FILE-0', missing.length === 0,
  missing.length ? `missing: ${missing.join(', ')}` : `${REQUIRED.length} SEO artifacts present`);

const SRC = Object.fromEntries(REQUIRED.filter(exists).map((f) => [f, strip(read(f))]));
const RAW = Object.fromEntries(REQUIRED.filter(exists).map((f) => [f, read(f)]));
const site = SRC['lib/site.ts'];
const layout = SRC['app/layout.tsx'];

// ------------------------------------------------------------
// 1. One metadata source of truth, unique titles/descriptions
// ------------------------------------------------------------
function metaPair(key) {
  // Scope to the SEO block: SITE already contains a different `download:` key.
  const block = site.slice(site.indexOf('export const SEO'));
  const re = new RegExp(`${key}:\\s*\\{[\\s\\S]*?title:\\s*'([^']+)'[\\s\\S]*?description:\\s*'([^']+)'`);
  const m = block.match(re);
  return m ? { title: m[1], description: m[2] } : null;
}
const pairs = Object.fromEntries(ROUTES.map(({ key }) => [key, metaPair(key)]));
const allPairs = Object.values(pairs);
check('M-1', allPairs.every(Boolean),
  `SEO map defines all 5 route pairs (${ROUTES.map((r) => r.key).join(', ')})`,
  loc('lib/site.ts', 'export const SEO'));
const titles = allPairs.filter(Boolean).map((p) => p.title);
const descs = allPairs.filter(Boolean).map((p) => p.description);
check('M-2', new Set(titles).size === titles.length && new Set(descs).size === descs.length,
  `${titles.length} unique titles / ${descs.length} unique descriptions`, loc('lib/site.ts', 'home:'));
check('M-3', /ogImage:\s*'\/opengraph-image'/.test(site) && /lastModified:\s*'\d{4}-\d{2}-\d{2}'/.test(site),
  'ogImage path + stable lastModified constant present', loc('lib/site.ts', 'ogImage:'));

// ------------------------------------------------------------
// 2. Root layout metadata (canonical / OG / Twitter / robots / hreflang)
// ------------------------------------------------------------
const rootMeta = [
  ['metadataBase', /metadataBase:\s*new URL\(SITE\.siteUrl\)/],
  ['title.default', /title:\s*\{\s*default:\s*TITLE/],
  ['home title source', /const TITLE = SEO\.home\.title/],
  ['home description source', /const DESCRIPTION = SEO\.home\.description/],
  ['og image source', /const OG_IMAGE = SEO\.ogImage/],
  ['description', /description:\s*DESCRIPTION/],
  ['canonical', /canonical:\s*'\/'/],
  ['hreflang ar/en/x-default', /languages:\s*\{\s*ar:\s*'\/',\s*en:\s*'\/',\s*'x-default':\s*'\/'/],
  ['og:type', /type:\s*'website'/],
  ['og:title', /title:\s*TITLE/],
  ['og:description', /description:\s*DESCRIPTION/],
  ['og:url', /url:\s*SITE\.siteUrl/],
  ['og:image 1200x630', /width:\s*1200,\s*height:\s*630/],
  ['twitter card', /card:\s*'summary_large_image'/],
  ['robots index', /index:\s*true,\s*follow:\s*true/],
];
const rootMissing = rootMeta.filter(([, re]) => !re.test(layout)).map(([n]) => n);
check('ROOT-1', rootMissing.length === 0,
  rootMissing.length ? `missing: ${rootMissing.join(', ')}` : `all ${rootMeta.length} root metadata fields present`,
  loc('app/layout.tsx', 'export const metadata'));
check('ROOT-2', /<html lang="ar" dir="rtl"/.test(RAW['app/layout.tsx']),
  'document starts lang=ar dir=rtl (LangProvider switches to en/ltr)', loc('app/layout.tsx', '<html lang='));
const i18n = exists('lib/i18n.tsx') ? read('lib/i18n.tsx') : '';
check('ROOT-3', /document\.documentElement\.lang\s*=\s*lang/.test(i18n) && /document\.documentElement\.dir\s*=\s*dir/.test(i18n),
  'client language toggle updates <html lang/dir> for fully-English mode',
  exists('lib/i18n.tsx') ? `website/lib/i18n.tsx:${lineOf(i18n, 'document.documentElement.lang')}` : 'website/lib/i18n.tsx:?');

// ------------------------------------------------------------
// 3. Per-page metadata (rendered through server layouts / page)
// ------------------------------------------------------------
for (const { route, key, file } of ROUTES) {
  const src = SRC[file];
  const p = pairs[key];
  // The root layout defines home via const TITLE/DESCRIPTION/OG_IMAGE; child
  // layouts and the download page reference SEO.<key> fields directly.
  const titleRef = key === 'home' ? 'SEO.home.title' : `SEO.${key}.title`;
  const descRef = key === 'home' ? 'DESCRIPTION' : `SEO.${key}.description`;
  const imageRef = key === 'home' ? 'OG_IMAGE' : 'SEO.ogImage';
  const ok = !!p
    && src.includes(titleRef)
    && src.includes(descRef)
    && src.includes(`canonical: '${route}'`)
    && src.includes(`languages: { ar: '${route}', en: '${route}', 'x-default': '${route}' }`)
    && src.includes('openGraph: {')
    && src.includes('twitter: {')
    && src.includes(`url: ${imageRef}`);
  check(`PAGE-${key}`, ok,
    ok ? `title/description/canonical=${route} / OG / Twitter / hreflang wired to SEO.${key}`
      : `incomplete metadata wiring for ${route} in ${file}`,
    loc(file, 'export const metadata'));
}

// ------------------------------------------------------------
// 4. Structured data — truthful, no fake price, no rating
// ------------------------------------------------------------
const schemaChecks = [
  ['Organization', /'@type':\s*'Organization'/],
  ['SoftwareApplication', /'@type':\s*'SoftwareApplication'/],
  ['FAQPage', /'@type':\s*'FAQPage'/],
  ['publisher @id', /publisher:\s*\{ '@id':/],
  ['free offer', /price:\s*0/],
  ['isAccessibleForFree', /isAccessibleForFree:\s*true/],
  ['3 ld+json scripts', /type="application\/ld\+json"/g],
];
let schemaOk = true;
for (const [name, re] of schemaChecks) {
  const hit = name === '3 ld+json scripts'
    ? (layout.match(re) || []).length >= 3
    : re.test(layout);
  if (!hit) { schemaOk = false; note(`LD-${name}`, 'FAIL', `missing ${name}`, loc('app/layout.tsx', '@context')); }
}
const fakePrice = /aggregateRating|price:\s*(?:79|99)\b|reviewRating|ratingValue/.test(layout);
check('LD-1', schemaOk && !fakePrice,
  schemaOk && !fakePrice
    ? 'Organization + SoftwareApplication + FAQPage, $0 FREE_SEASON offer, no rating/paid price claim'
    : `schema incomplete or fake claim present (fakePrice=${fakePrice})`,
  loc('app/layout.tsx', 'ORGANIZATION_SCHEMA'));

// ------------------------------------------------------------
// 5. Semantic HTML + bilingual content
// ------------------------------------------------------------
const H1_FILES = [
  'app/page.tsx', 'app/features/page.tsx', 'app/pricing/page.tsx',
  'app/docs/page.tsx',
];
let h1Ok = true;
for (const f of H1_FILES) {
  const n = (SRC[f].match(/<h1\b/g) || []).length;
  const h2 = (SRC[f].match(/<h2\b/g) || []).length;
  const ok = n === 1 && h2 >= 1;
  if (!ok) h1Ok = false;
  note(`H1-${path.basename(path.dirname(f))}`, ok ? 'PASS' : 'FAIL',
    `${n} h1 / ${h2} h2`, `${f}:${lineOf(SRC[f], '<h1')}`);
}
const dl = exists('components/download/DownloadPage.tsx') ? strip(read('components/download/DownloadPage.tsx')) : '';
const dlH1 = (dl.match(/<h1\b/g) || []).length;
check('H1-download', dlH1 === 1, `exactly one h1 in download flow (${dlH1})`,
  `website/components/download/DownloadPage.tsx:${lineOf(dl, '<h1')}`);
check('H1-all', h1Ok, 'one h1 per owned page with h2 subsections');

const chrome = exists('components/chrome.tsx') ? read('components/chrome.tsx') : '';
check('A11Y-1', /<nav className="nav"/.test(chrome) && /<footer/.test(chrome) && /<main>\{children\}<\/main>/.test(RAW['app/layout.tsx']),
  'nav + footer + main landmarks present',
  loc('app/layout.tsx', '<main>'));
check('A11Y-2', /<img[^>]+alt=/.test(chrome) && /aria-hidden="true"/.test(RAW['app/page.tsx']),
  'image alt text and decorative SVG aria-hidden present',
  exists('components/chrome.tsx') ? `website/components/chrome.tsx:${lineOf(chrome, '<img')}` : 'website/components/chrome.tsx:?');
const pageFiles = [...H1_FILES, 'app/download/page.tsx', 'components/download/DownloadPage.tsx'];
const bilingualOk = pageFiles.filter(exists).every((f) => {
  const s = RAW[f] || read(f);
  return arabic(s) && /[A-Za-z]{4,}/.test(s);
});
check('LANG-1', bilingualOk,
  'every public page carries both Arabic and English copy (bilingual)', loc('app/page.tsx', 'HERO'));

// ------------------------------------------------------------
// 6. No false claims in metadata
// ------------------------------------------------------------
const banned = /\b(unbeatable|best-in-class|world-class|guaranteed|perfect|number one|#1)\b/i;
const metaText = Object.values(pairs).filter(Boolean).flatMap((p) => [p.title, p.description]).join(' ')
  + ' ' + (site.match(/ogImageAlt:\s*'([^']+)'/)?.[1] || '');
check('TRUTH-1', !banned.test(metaText),
  'no superlative/fake claims in titles, descriptions or OG alt', loc('lib/site.ts', 'home:'));

// ------------------------------------------------------------
// 7. Sitemap + robots (source)
// ------------------------------------------------------------
const sitemap = SRC['app/sitemap.ts'];
const sitemapRoutesOk = SITEMAP_ROUTES.every((p) =>
  sitemap.includes(`path: '${p}'`));
check('SM-1', sitemapRoutesOk,
  `sitemap lists all ${SITEMAP_ROUTES.length} public routes`, loc('app/sitemap.ts', 'const PAGES'));
check('SM-2', /const lastModified = SEO\.lastModified/.test(sitemap) && !/new Date\s*\(/.test(sitemap),
  'stable lastModified from SEO constant, no build-time churn', loc('app/sitemap.ts', 'const lastModified'));
check('SM-3', /SITE\.siteUrl\.replace/.test(sitemap) && !/vercel\.app/.test(sitemap),
  'sitemap URLs use canonical domain only', loc('app/sitemap.ts', 'const base'));

const robots = SRC['app/robots.ts'];
check('ROBOTS-1', /allow:\s*'\/'/.test(robots) && /sitemap:\s*`\$\{base\}\/sitemap\.xml`/.test(robots),
  'crawlers allowed, sitemap URL emitted', loc('app/robots.ts', 'rules:'));
check('ROBOTS-2', !/disallow/.test(robots),
  'no public route blocked (all sitemap URLs crawlable)', loc('app/robots.ts', 'userAgent:'));

// ------------------------------------------------------------
// 8. Real OG image
// ------------------------------------------------------------
const og = SRC['app/opengraph-image.tsx'];
check('OGIMG-1', /ImageResponse/.test(og) && /width:\s*1200,\s*height:\s*630/.test(og)
  && /contentType\s*=\s*'image\/png'/.test(og) && /export const alt/.test(og),
  'ImageResponse generates a 1200x630 PNG with alt text', loc('app/opengraph-image.tsx', 'ImageResponse'));

// ------------------------------------------------------------
// 9. Rendered build artifacts (when present)
// ------------------------------------------------------------
if (!fs.existsSync(BUILD)) {
  note('BUILD-0', 'SKIP', 'website/.next not found — run npm run build for rendered-head checks');
} else {
  fs.readdirSync(BUILD).filter((f) => f.endsWith('.html')).length;
  for (const { route, build } of ROUTES) {
    const f = path.join(BUILD, build);
    if (!fs.existsSync(f)) { note(`BUILD-${build}`, 'FAIL', 'prerendered HTML missing', `.next/server/app/${build}`); continue; }
    const html = fs.readFileSync(f, 'utf8');
    // metadataBase + '/' renders the root canonical as the bare origin.
    const canonical = route === '/' ? SITE_URL : `${SITE_URL}${route}`;
    const ok = /<title>[^<]+<\/title>/.test(html)
      && /<meta name="description" content="[^"]+"/.test(html)
      && html.includes(`<link rel="canonical" href="${canonical}"/>`)
      && html.includes('property="og:title"')
      && html.includes('property="og:image"')
      && html.includes('name="twitter:card"')
      && /hrefLang="ar"/i.test(html) && /hrefLang="en"/i.test(html)
      && html.includes('"@type":"Organization"')
      && html.includes('"@type":"SoftwareApplication"')
      && html.includes('"@type":"FAQPage"');
    check(`BUILD-${build}`, ok,
      ok ? `rendered head has title/desc/canonical/OG/Twitter/hreflang + 3 JSON-LD types (${route})`
        : `rendered head incomplete for ${route}`, `.next/server/app/${build}`);
  }
  const rb = path.join(BUILD, 'robots.txt.body');
  const sm = path.join(BUILD, 'sitemap.xml.body');
  const ogb = path.join(BUILD, 'opengraph-image.body');
  if (fs.existsSync(rb)) {
    const t = fs.readFileSync(rb, 'utf8');
    check('BUILD-robots', /Allow: \//.test(t) && t.includes(`Sitemap: ${SITE_URL}/sitemap.xml`),
      'rendered robots.txt allows crawlers and points to sitemap', '.next/server/app/robots.txt.body');
  } else note('BUILD-robots', 'FAIL', 'robots.txt.body missing');
  if (fs.existsSync(sm)) {
    const t = fs.readFileSync(sm, 'utf8');
    const ok = SITEMAP_ROUTES.every((p) => t.includes(`<loc>${SITE_URL}${p}</loc>`))
      && (t.match(/<lastmod>/g) || []).length === SITEMAP_ROUTES.length;
    check('BUILD-sitemap', ok, `${SITEMAP_ROUTES.length} loc + lastmod entries in rendered XML`,
      '.next/server/app/sitemap.xml.body');
  } else note('BUILD-sitemap', 'FAIL', 'sitemap.xml.body missing');
  if (fs.existsSync(ogb)) {
    const b = fs.readFileSync(ogb);
    const png = b.subarray(0, 8).toString('hex') === '89504e470d0a1a0a';
    const w = b.readUInt32BE(16), h = b.readUInt32BE(20);
    check('BUILD-ogimage', png && w === 1200 && h === 630,
      `rendered OG image is a real PNG (${w}x${h}, ${b.length} bytes)`, '.next/server/app/opengraph-image.body');
  } else note('BUILD-ogimage', 'FAIL', 'opengraph-image.body missing');
}

// ------------------------------------------------------------
// Output
// ------------------------------------------------------------
const fails = results.filter((r) => r.status === 'FAIL').length;
const passes = results.filter((r) => r.status === 'PASS').length;
const skips = results.filter((r) => r.status === 'SKIP').length;
console.log('');
console.log(`RESULT: ${passes} PASS / ${fails} FAIL / ${skips} SKIP`);
console.log('Scope: website metadata + structured data only. No deploy performed.');
process.exit(fails ? 1 : 0);
